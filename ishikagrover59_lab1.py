class VAE(nn.Module):

    def __init__(self):
        super().__init__()

        self.encoder = nn.Sequential(
            nn.Flatten(),
            nn.Linear(784, 256),
            nn.ReLU()
        )

        self.mean = nn.Linear(256, 2)
        self.logvar = nn.Linear(256, 2)

        self.decoder = nn.Sequential(
            nn.Linear(2, 256),
            nn.ReLU(),
            nn.Linear(256, 784),
            nn.Sigmoid()
        )

    def encode(self, x):
        h = self.encoder(x)
        return self.mean(h), self.logvar(h)

    def forward(self, x):
        mu, logvar = self.encode(x)

        z = mu + torch.exp(0.5 * logvar) * torch.randn_like(mu)

        return self.decoder(z), mu, logvar


vae = VAE().to(device)

optimizer = torch.optim.Adam(
    vae.parameters(),
    lr=0.001
)

print(vae)

for epoch in range(1, 6):

    vae.train()

    totals = {
        "reconstruction": 0.0,
        "kl": 0.0
    }

    for x, _ in loader:

        x = x.to(device)

        generated, mu, logvar = vae(x)

        recon = F.binary_cross_entropy(
            generated,
            x.flatten(1),
            reduction="sum"
        )

        kl = -0.5 * (
            1 + logvar - mu.square() - logvar.exp()
        ).sum()

        loss = (recon + kl) / x.size(0)

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        totals["reconstruction"] += recon.item()
        totals["kl"] += kl.item()

    print(
        epoch,
        {
            k: round(v / len(train), 2)
            for k, v in totals.items()
        }
    )

torch.save(vae.state_dict(), out / "vae_mnist.pt")

